async def fetch_rates(base="USD"):
    url1 = JSDELIVR.format(base=base.lower())
    try:
        async with aiohttp.ClientSession() as session:
            async with session.get(url1, timeout=5) as resp:
                resp.raise_for_status()
                return await resp.json()
    except Exception:
        url2 = CLOUD_FLARE.format(base=base.lower())
        async with aiohttp.ClientSession() as session:
            async with session.get(url2, timeout=5) as resp:
                resp.raise_for_status()
                return await resp.json()

async def convert(base: str, amount: float, target: str):
    data = await fetch_rates(base)
    rate = data.get(base.lower(), {}).get(target.lower())
    if rate is None:
        print(f"Couldn't find rate for {target}")
        return
    converted = amount * rate
    return converted